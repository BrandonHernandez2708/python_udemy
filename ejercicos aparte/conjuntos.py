# Dado dos conjuntos:
A = {1, 2, 3, 4}  
B = {3, 4, 5, 6}
# Realiza:
# Unión
union= A | B
print("Unión:", union)
# Intersección
interseccion = A & B
print("Intersección:", interseccion)

# Diferencia simétrica
diferencia_simetrica = A ^ B
print("Diferencia simétrica:", diferencia_simetrica)
# Verifica si el número 2 está en el conjunto A.
if 2 in A:
    print("2 está en el conjunto A")
else:
    print("2 no está en el conjunto A")





